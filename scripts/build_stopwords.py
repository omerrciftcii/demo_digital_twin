"""Write the Turkish stopword list used by text retrieval.

The words come from the Apache Lucene TurkishAnalyzer default list
(LUCENE-559 merged with the JASIST 2008 Turkish IR list). The script
downloads that file and writes the folded words. It does not add or
remove any word.
"""

from __future__ import annotations

import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from medical_ai_selective_context.index import normalize_text

SOURCE = (
    "https://raw.githubusercontent.com/apache/lucene/main/"
    "lucene/analysis/common/src/resources/org/apache/lucene/analysis/tr/stopwords.txt"
)
DESTINATION = ROOT / "src" / "medical_ai_selective_context" / "data" / "stopwords-tr.txt"
HEADER = """# Generated by scripts/build_stopwords.py. Do not edit by hand.
# Source: Apache Lucene TurkishAnalyzer default stopwords (LUCENE-559, JASIST 2008)
# https://github.com/apache/lucene/blob/main/lucene/analysis/common/src/resources/org/apache/lucene/analysis/tr/stopwords.txt
"""


def words_from(text: str) -> list[str]:
    found: list[str] = []
    seen: set[str] = set()
    for line in text.splitlines():
        raw = line.strip()
        if not raw or raw.startswith("#"):
            continue
        word = normalize_text(raw)
        if len(word) < 2 or word in seen:
            continue
        seen.add(word)
        found.append(word)
    found.sort()
    return found


def main() -> None:
    with urllib.request.urlopen(SOURCE, timeout=60) as response:
        payload = response.read().decode("utf-8")
    rows = words_from(payload)
    if len(rows) < 100:
        raise SystemExit(f"stopword download looks truncated ({len(rows)} words)")
    DESTINATION.parent.mkdir(parents=True, exist_ok=True)
    DESTINATION.write_text(HEADER + "\n".join(rows) + "\n", encoding="utf-8")
    print(f"wrote {len(rows)} stopwords to {DESTINATION}")


if __name__ == "__main__":
    main()
