"""Offline, source-grounded retrieval evaluation; never invokes a chat model."""

import json
import math
import re
import statistics
import time
from collections import Counter
from pathlib import Path
from typing import Any, Literal

from pydantic import BaseModel, ConfigDict, Field, field_validator

from .evidence import build_evidence, resolve_pointer
from .index import EvidenceIndex
from .selector import select_context
from .store import content_hash, unwrap_and_validate_cco

_EVIDENCE_POINTER = re.compile(
    r"^/sections/(?:[^~/]|~[01])+/((?:facts|insights)/(?:0|[1-9][0-9]*))"
    r"(?:/facts/(?:0|[1-9][0-9]*))?$"
)


class EvaluationCase(BaseModel):
    model_config = ConfigDict(extra="forbid", strict=True)

    caseId: str = Field(min_length=1, max_length=128)
    ccoFile: str = Field(min_length=1, max_length=1024)
    question: str = Field(min_length=1, max_length=16000)
    requiredSourcePointers: list[str] = Field(max_length=2000)
    critical: bool
    reviewStatus: Literal["unreviewed", "reviewed"]
    failureOrigin: Literal["retrieval", "missing_in_cco", "unknown"]

    @field_validator("question", "caseId")
    @classmethod
    def nonempty_text(cls, value: str) -> str:
        if not value.strip():
            raise ValueError("Text must not be blank")
        return value

    @field_validator("requiredSourcePointers")
    @classmethod
    def source_roots_only(cls, value: list[str]) -> list[str]:
        if len(set(value)) != len(value):
            raise ValueError("Required pointers must be unique")
        for pointer in value:
            if (not _EVIDENCE_POINTER.fullmatch(pointer)
                    or re.search(r"/facts/[0-9]+/facts/", pointer)):
                raise ValueError("A required pointer must address an evidence root")
        return value


def _unique_pairs(pairs: list[tuple[str, Any]]) -> dict[str, Any]:
    result: dict[str, Any] = {}
    for key, value in pairs:
        if key in result:
            raise ValueError("Duplicate JSON property")
        result[key] = value
    return result


def read_cases(path: Path) -> list[EvaluationCase]:
    """Errors contain only a line number, never a question or clinical value."""
    cases = []
    seen = set()
    with path.open(encoding="utf-8-sig") as source:
        for number, line in enumerate(source, 1):
            if not line.strip():
                continue
            try:
                case = EvaluationCase.model_validate(json.loads(line, object_pairs_hook=_unique_pairs))
                if case.caseId in seen:
                    raise ValueError("Duplicate case ID")
            except (ValueError, TypeError) as exc:
                raise ValueError(f"Invalid evaluation annotation on line {number}") from exc
            seen.add(case.caseId)
            cases.append(case)
    return cases


def resolve_cco_file(name: str, dataset: Path, project_root: Path) -> Path:
    """Resolve only a dataset-local or project/data relative path, never a URL."""
    relative = Path(name)
    if relative.is_absolute() or ".." in relative.parts or ":" in name:
        raise ValueError("CCO path must be relative without parent traversal")
    roots = [dataset.resolve().parent, (project_root / "data").resolve()]
    candidates = list(dict.fromkeys([
        (dataset.resolve().parent / relative).resolve(),
        (project_root.resolve() / relative).resolve(),
    ]))
    matching = [candidate for candidate in candidates if candidate.is_file()
                and any(candidate.is_relative_to(root) for root in roots)]
    if len(matching) != 1:
        raise ValueError("CCO source is missing, outside permitted roots, or ambiguous")
    return matching[0]


def score_selection(document: dict[str, Any], case: EvaluationCase,
                    entries: list[dict[str, Any]], packet: dict[str, Any]) -> dict[str, Any]:
    """Missing input evidence is a data gap, not an algorithmic retrieval miss.

    This verifies selected source pointers/values, not the clinical correctness
    of a generated answer. No answer is generated by this evaluator.
    """
    source = {entry["sourcePointer"]: entry for entry in entries}
    selected = set()
    invalid_citations = 0
    for entry in packet.get("evidence", []):
        pointer = entry.get("sourcePointer")
        expected = source.get(pointer)
        try:
            original = resolve_pointer(document, pointer) if isinstance(pointer, str) else None
        except (KeyError, IndexError, ValueError, TypeError):
            original = None
        if (expected is None or original is None or entry.get("source") != original
                or any(entry.get(field) != expected.get(field) for field in (
                    "ref", "snapshotId", "sourceKind", "section", "definition", "definitionId",
                    "factId", "insightId", "value", "occurredFrom", "occurredTo", "recordedAt",
                    "producedAt", "validUntil", "evaluationKey", "evaluationStatus",
                    "comparisons", "evidence", "severity", "dependencies", "parentRef",
                ))):
            invalid_citations += 1
            continue
        selected.add(pointer)

    present, absent, invalid = [], [], []
    for pointer in case.requiredSourcePointers:
        try:
            resolve_pointer(document, pointer)
        except (KeyError, IndexError):
            absent.append(pointer)
        except (ValueError, TypeError):
            invalid.append(pointer)
        else:
            (present if pointer in source else invalid).append(pointer)
    matched = [pointer for pointer in present if pointer in selected]
    missed = [pointer for pointer in present if pointer not in selected]
    origins = []
    if missed:
        origins.append("retrieval")
    if absent:
        origins.append("missing_in_cco")
    if invalid:
        origins.append("invalid_annotation")
    label_mismatch = case.failureOrigin != "unknown" and case.failureOrigin not in origins
    return {
        "caseId": case.caseId, "reviewStatus": case.reviewStatus, "critical": case.critical,
        "requiredPresent": len(present), "matchedRequired": len(matched),
        "requiredEvidenceRecall": len(matched) / len(present) if present else None,
        "retrievalMisses": missed, "missingInCco": absent, "invalidAnnotations": invalid,
        "invalidSelectedCitations": invalid_citations,
        "observedFailureOrigins": origins, "annotatedFailureOrigin": case.failureOrigin,
        "failureAnnotationMismatch": label_mismatch,
        "emptyGoldSet": not case.requiredSourcePointers,
        "criticalRetrievalMisses": len(missed) if case.critical else 0,
        "criticalUpstreamGaps": len(absent) if case.critical else 0,
        "canAnswer": packet.get("canAnswer", False),
        "blockers": packet.get("blockers", []),
        "coverageStates": [item["state"] for item in packet.get("coverage", [])],
        "selectedEvidence": len(packet.get("evidence", [])),
        "tokenEstimate": packet.get("tokenEstimate"),
        "tokenEstimationMethod": packet.get("tokenEstimationMethod"),
    }


def _distribution(values: list[float]) -> dict[str, float | None]:
    if not values:
        return {"min": None, "median": None, "p95": None, "max": None}
    ordered = sorted(values)
    return {"min": min(values), "median": statistics.median(values),
            "p95": ordered[math.ceil(len(ordered) * .95) - 1], "max": max(values)}


def aggregate_results(results: list[dict[str, Any]], reviewed_subject_count: int) -> dict[str, Any]:
    def metrics(rows: list[dict[str, Any]]) -> dict[str, Any]:
        present = sum(row["requiredPresent"] for row in rows)
        matched = sum(row["matchedRequired"] for row in rows)
        return {
            "cases": len(rows), "requiredEvidence": present, "matchedRequiredEvidence": matched,
            "requiredEvidenceRecall": matched / present if present else None,
            "retrievalMisses": sum(len(row["retrievalMisses"]) for row in rows),
            "missingInCco": sum(len(row["missingInCco"]) for row in rows),
            "criticalRetrievalMisses": sum(row["criticalRetrievalMisses"] for row in rows),
            "criticalUpstreamGaps": sum(row["criticalUpstreamGaps"] for row in rows),
            "invalidSelectedCitations": sum(row["invalidSelectedCitations"] for row in rows),
            "invalidAnnotations": sum(len(row["invalidAnnotations"]) for row in rows),
            "emptyGoldSets": sum(row["emptyGoldSet"] for row in rows),
            "blockedCases": sum(not row["canAnswer"] for row in rows),
            "latencyMs": _distribution([row["selectionLatencyMs"] for row in rows
                                        if "selectionLatencyMs" in row]),
            "estimatedContextTokens": _distribution([row["tokenEstimate"] for row in rows
                                                       if row.get("tokenEstimate") is not None]),
        }

    reviewed_rows = [row for row in results if row["reviewStatus"] == "reviewed"]
    reviewed = metrics(reviewed_rows)
    reasons = []
    for failed, reason in (
        (reviewed["cases"] < 100, "fewer_than_100_reviewed_cases"),
        (reviewed_subject_count < 15, "fewer_than_15_reviewed_subjects"),
        (reviewed["requiredEvidenceRecall"] is None, "no_reviewed_required_evidence"),
        ((reviewed["requiredEvidenceRecall"] or 0) < .95, "reviewed_recall_below_95_percent"),
        (reviewed["criticalRetrievalMisses"] > 0, "critical_retrieval_misses"),
        (reviewed["missingInCco"] > 0, "unresolved_upstream_data_gaps"),
        (reviewed["invalidSelectedCitations"] > 0, "invalid_selected_citations"),
        (reviewed["invalidAnnotations"] > 0, "invalid_annotations"),
        (reviewed["emptyGoldSets"] > 0, "empty_gold_sets_not_scorable"),
        (not any(row["critical"] for row in reviewed_rows), "no_reviewed_critical_cases"),
    ):
        if failed:
            reasons.append(reason)
    return {
        "allCases": metrics(results), "reviewedCases": reviewed,
        "reviewedUniqueSubjects": reviewed_subject_count,
        "retrievalAcceptance": {"passed": not reasons, "reasons": reasons},
        "clinicalProductionValidated": False,
        "answerQualityEvaluated": False,
    }


def evaluate_dataset(dataset: Path, project_root: Path, work_dir: Path,
                     *, semantic: bool = False, token_budget: int = 8000) -> dict[str, Any]:
    cases = read_cases(dataset)
    index = EvidenceIndex(work_dir / "evidence.sqlite3",
                          embedding_model="intfloat/multilingual-e5-small" if semantic else "")
    loaded: dict[Path, tuple[dict, str, list]] = {}
    reviewed_subjects = set()
    results = []
    index_ms = 0.0
    try:
        for number, case in enumerate(cases, 1):
            try:
                path = resolve_cco_file(case.ccoFile, dataset, project_root)
                if path not in loaded:
                    start = time.perf_counter()
                    document = unwrap_and_validate_cco(json.loads(
                        path.read_text(encoding="utf-8-sig"), object_pairs_hook=_unique_pairs
                    ))
                    snapshot_id = "cco_" + content_hash(document)
                    entries = build_evidence(document, snapshot_id)
                    index.index_snapshot(snapshot_id, entries)
                    loaded[path] = document, snapshot_id, entries
                    index_ms += (time.perf_counter() - start) * 1000
                document, snapshot_id, entries = loaded[path]
                start = time.perf_counter()
                ranked = index.search(snapshot_id, [case.question])
                packet = select_context(document, case.question, entries, ranked,
                                        snapshot_id=snapshot_id, token_budget=token_budget,
                                        graph_status={"status": "not_used_offline_evaluation"})
                selection_ms = (time.perf_counter() - start) * 1000
                result = score_selection(document, case, entries, packet)
                result["selectionLatencyMs"] = round(selection_ms, 3)
                results.append(result)
                if case.reviewStatus == "reviewed":
                    reviewed_subjects.add(document["subjectId"].casefold())
            except (OSError, ValueError, TypeError, KeyError) as exc:
                raise ValueError(f"Evaluation failed at case number {number}") from exc
        counts = Counter(item["reviewStatus"] for item in results)
        return {
            "schemaVersion": "retrieval-evaluation/1.0",
            "mode": "offline_source_selection_only", "modelApiCalls": 0,
            "tokenBudget": token_budget,
            "queryPlanner": "raw_question_no_llm_or_terminology_expansion",
            "semanticRequested": semantic, "index": index.status(),
            "indexingLatencyMs": round(index_ms, 3),
            "snapshotCount": len({value[1] for value in loaded.values()}),
            "reviewStatusCounts": dict(counts),
            **aggregate_results(results, len(reviewed_subjects)), "results": results,
        }
    finally:
        index.close()
